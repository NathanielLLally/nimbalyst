#!/bin/bash
# Git steps shared by deploy.sh and deploy_prod.sh. Source this file; don't run it.
# server_sync is shipped to the server with `declare -f`, so it must stay self-contained.
# Tests: bash test/test-deploy-git-sync.sh

# Local dev box: commit everything, merge in whatever origin has, then push.
# A plain `git push` is rejected whenever origin moved on (e.g. a deploy from the
# other machine), which killed the deploy and left the merge to be done by hand.
local_sync() {
  cd "$1" || return 1
  git add -A
  git commit -m "$(date "+%Y-%m-%d %H:%M")" || echo "No changes to commit"
  if ! git pull --no-rebase --no-edit; then
    git merge --abort 2>/dev/null || true
    echo "❌ Could not merge origin into $1 (conflict or network error)." >&2
    echo "   Your commit is kept locally. Run 'git pull', resolve, then re-run the deploy." >&2
    return 1
  fi
  git push
}

# Server checkout: fast-forward to origin. Never merges or discards hand edits.
server_sync() {
  cd "$1" || return 1
  # The previous deploy's `npm install` rewrites package-lock.json; that churn
  # would block the pull, and it is regenerated by the install below anyway.
  git checkout -- package-lock.json 2>/dev/null || true
  if ! git pull --ff-only; then
    echo "❌ git pull failed in $1 — the server checkout has local changes or commits." >&2
    echo "   Inspect with: git -C $1 status && git -C $1 log --oneline origin/main..HEAD" >&2
    return 1
  fi
}
